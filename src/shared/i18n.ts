export const dictionaries: Record<Locale, Record<TranslationKey, string>> = {
  'zh-CN': zhCN,
  en
};

let activeLocale: Locale = 'zh-CN';

export function isLocale(value: unknown): value is Locale {
  return value === 'zh-CN' || value === 'en';
}

/** Map Electron's locale hints. A Chinese hint wins; unavailable or unusable hints fall back to Chinese. */
export function systemLocaleToLocale(systemLocale?: unknown, preferredLanguages?: unknown): Locale {
  const hints: string[] = [];
  if (typeof systemLocale === 'string' && systemLocale.trim()) hints.push(systemLocale.trim());
  if (Array.isArray(preferredLanguages)) {
    for (const hint of preferredLanguages) {
      if (typeof hint === 'string' && hint.trim()) hints.push(hint.trim());
    }
  }
  if (hints.some(hint => /^zh/i.test(hint))) return 'zh-CN';
  if (hints.some(hint => /^[a-z]{2,3}(?:[-_][a-z0-9]+)*$/i.test(hint))) return 'en';
  return 'zh-CN';
}

export function setI18nLocale(locale: Locale): void {
  activeLocale = locale;
}

export function getI18nLocale(): Locale {
  return activeLocale;
}

export function t(key: TranslationKey, params: Record<string, string | number> = {}, locale = activeLocale): string {
  const template = dictionaries[locale][key];
  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (placeholder, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : placeholder
  );
}

/** Session records may contain the Chinese default title created by the CLI integration. */
export function isDefaultSessionTitle(value: string | undefined): boolean {
  return value === zhCN['chat.defaultSessionTitle'] || value === en['chat.defaultSessionTitle'];
}

export interface TranslationElement {
  textContent: string | null;
  getAttribute(name: string): string | null;
  setAttribute(name: string, value: string): void;
}

export interface TranslationRoot {
  querySelectorAll(selector: string): ArrayLike<TranslationElement>;
  documentElement?: TranslationElement;
}

/** Reapply dictionary-backed static HTML attributes without replacing DOM nodes. */
export function applyStaticTranslations(root: TranslationRoot, locale = activeLocale): void {
  const elements = root.querySelectorAll('[data-i18n], [data-i18n-title], [data-i18n-aria], [data-i18n-placeholder]');
  for (let index = 0; index < elements.length; index += 1) {
    const element = elements[index];
    if (!element) continue;
    const textKey = element.getAttribute('data-i18n') as TranslationKey | null;
    const titleKey = element.getAttribute('data-i18n-title') as TranslationKey | null;
    const ariaKey = element.getAttribute('data-i18n-aria') as TranslationKey | null;
    const placeholderKey = element.getAttribute('data-i18n-placeholder') as TranslationKey | null;
    if (textKey) element.textContent = t(textKey, {}, locale);
    if (titleKey) element.setAttribute('title', t(titleKey, {}, locale));
    if (ariaKey) element.setAttribute('aria-label', t(ariaKey, {}, locale));
    if (placeholderKey) element.setAttribute('placeholder', t(placeholderKey, {}, locale));
  }
  root.documentElement?.setAttribute('lang', locale);
}

/** Select an English singular/plural form while keeping Chinese counts compact. */
export function plural(count: number, zhCNForm: string, enSingular: string, enPlural = enSingular): string {
  const template = activeLocale === 'zh-CN' ? zhCNForm : count === 1 ? enSingular : enPlural;
  return template.replace(/\{count\}/g, String(count));
}
